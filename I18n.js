function t(lang, key) {
  var table = STRINGS[lang] || STRINGS.en
  var s = table[key] !== undefined ? table[key] : (STRINGS.en[key] !== undefined ? STRINGS.en[key] : key)
  for (var i = 2; i < arguments.length; i++) s = s.split("%" + (i - 1)).join(String(arguments[i]))
  return s
}

// Translates a binding description; families get their number filled in.
function desc(lang, template, n) {
  var text = template
  if (lang === "it" && DESC_IT[template] !== undefined) text = DESC_IT[template]
  if (n !== null && n !== undefined) text = text.split("#").join(String(n))
  return text
}

function defaultLang(localeName) {
  return String(localeName || "").indexOf("it") === 0 ? "it" : "en"
}
